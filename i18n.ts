// Digits converter based on NumberSystem
export function formatDigits(val: number | string, system: NumberSystem = 'persian'): string {
  const str = String(val);
  if (system === 'latin') {
    return str.replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d))).replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
  }

  const persianMap = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
  const arabicMap = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

  if (system === 'arabic') {
    return str.replace(/\d/g, (d) => arabicMap[parseInt(d, 10)]);
  }

  // default persian
  return str.replace(/\d/g, (d) => persianMap[parseInt(d, 10)]);
}

export function t(key: string, lang: AppLanguage = 'fa'): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fa;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
